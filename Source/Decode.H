#ifndef _DECODE_H
#define _DECODE_H
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

#include <string>

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

//Produces a field-by-field description of a captured IP packet: the IPv4/IPv6 header (and extension headers), the
//	TCP/UDP/ICMP header, and where the payload is DNS, HTTP or TLS, a decode of that too. Lines end in CRLF.
void DecodePacketText(const char *sPacket, int iSize, std::string *pOut);

//Formats a classic hex dump: offset, 16 bytes per line, and an ASCII gutter.
void HexDumpText(const char *sData, int iSize, std::string *pOut);

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
#endif
